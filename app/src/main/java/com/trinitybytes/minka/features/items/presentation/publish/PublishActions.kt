package com.trinitybytes.minka.features.items.presentation.publish

import com.trinitybytes.minka.features.items.domain.Category
import com.trinitybytes.minka.features.items.domain.Condition

/** Everything the Publicar screens can ask for; the defaults do nothing, which keeps previews and tests short. */
data class PublishActions(
    val onClose: () -> Unit = {},
    val onLeave: () -> Unit = {},
    val onBack: () -> Unit = {},
    val onContinue: () -> Unit = {},
    val onSaveDraft: () -> Unit = {},
    val onPublish: () -> Unit = {},
    val onEdit: (PublishPage) -> Unit = {},
    val onAddPhotos: () -> Unit = {},
    val onPhotoTapped: (Int) -> Unit = {},
    val onPhotoRemoved: (Int) -> Unit = {},
    val onMakeCover: (Int) -> Unit = {},
    val onTitleChange: (String) -> Unit = {},
    val onCategoryRowTapped: () -> Unit = {},
    val onCategoryChosen: (Category) -> Unit = {},
    val onConditionChosen: (Condition) -> Unit = {},
    val onDetailsTapped: () -> Unit = {},
    val onDetailsDone: (description: String, estimatedSoles: String) -> Unit = { _, _ -> },
    val onWantToggled: (Category) -> Unit = {},
    val onDistrictRowTapped: () -> Unit = {},
    val onDistrictChosen: (String) -> Unit = {},
    val onMeetingPointRowTapped: () -> Unit = {},
    val onMeetingPointDone: (String) -> Unit = {},
    val onHideLocationChange: (Boolean) -> Unit = {},
    val onHomeDeliveryChange: (Boolean) -> Unit = {},
    val onTakePhoto: () -> Unit = {},
    val onPickFromGallery: () -> Unit = {},
    val onDismissOverlay: () -> Unit = {},
    val onExitSave: () -> Unit = {},
    val onExitDiscard: () -> Unit = {},
    val onViewListing: (String) -> Unit = {},
    val onShare: () -> Unit = {},
    val onPublishAnother: () -> Unit = {},
    val onRetryLoad: () -> Unit = {},
    val onMessageShown: () -> Unit = {},
)

/** The actions that talk to [viewModel]; the platform ones (camera, picker, share, leaving) come from the screen. */
internal fun publishActionsOf(
    viewModel: PublishViewModel,
    onLeave: () -> Unit,
    onTakePhoto: () -> Unit,
    onPickFromGallery: () -> Unit,
    onViewListing: (String) -> Unit,
    onShare: () -> Unit,
) = PublishActions(
    onClose = viewModel::onClose,
    onLeave = onLeave,
    onBack = viewModel::onBack,
    onContinue = viewModel::onContinue,
    onSaveDraft = viewModel::onSaveDraft,
    onPublish = viewModel::onPublish,
    onEdit = viewModel::onEdit,
    onAddPhotos = viewModel::onAddPhotosTapped,
    onPhotoTapped = viewModel::onPhotoTapped,
    onPhotoRemoved = viewModel::onPhotoRemoved,
    onMakeCover = viewModel::onMakeCover,
    onTitleChange = viewModel::onTitleChange,
    onCategoryRowTapped = viewModel::onCategoryRowTapped,
    onCategoryChosen = viewModel::onCategoryChosen,
    onConditionChosen = viewModel::onConditionChosen,
    onDetailsTapped = viewModel::onDetailsTapped,
    onDetailsDone = viewModel::onDetailsDone,
    onWantToggled = viewModel::onWantToggled,
    onDistrictRowTapped = viewModel::onDistrictRowTapped,
    onDistrictChosen = viewModel::onDistrictChosen,
    onMeetingPointRowTapped = viewModel::onMeetingPointRowTapped,
    onMeetingPointDone = viewModel::onMeetingPointDone,
    onHideLocationChange = viewModel::onHideLocationChange,
    onHomeDeliveryChange = viewModel::onHomeDeliveryChange,
    onTakePhoto = onTakePhoto,
    onPickFromGallery = onPickFromGallery,
    onDismissOverlay = viewModel::dismissOverlay,
    onExitSave = viewModel::onExitSave,
    onExitDiscard = viewModel::onExitDiscard,
    onViewListing = onViewListing,
    onShare = onShare,
    onPublishAnother = viewModel::onPublishAnother,
    onRetryLoad = viewModel::onRetryLoad,
    onMessageShown = viewModel::onMessageShown,
)
